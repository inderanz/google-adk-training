const fs = require('node:fs/promises');
const path = require('node:path');
const {BASE, sourcePolicy, isolatedPolicy, unique, routeForFile} = require('./policy.cjs');

async function files(dir, prefix = '') {
  const found = [];
  for (const item of await fs.readdir(dir, {withFileTypes: true})) {
    const name = path.posix.join(prefix, item.name);
    if (item.isDirectory()) found.push(...await files(path.join(dir, item.name), name));
    else found.push(name);
  }
  return found;
}

module.exports = function portalPlugin(context) {
  let chunks = {};
  let emitted = {};
  return {
    name: 'gyanhq-protected-assets',
    configureWebpack(config, isServer) {
      // Mutate only this explicitly selected build profile.
      config.devtool = false;
      // Docusaurus' default cache name is shared across config profiles. Do not
      // reuse modules resolved against the public site's generated config.
      config.cache = false;
      config.resolve.alias['@docusaurus/Link'] = path.join(__dirname, 'Link.jsx');
      if (!isServer) {
        config.optimization.concatenateModules = false;
        config.optimization.splitChunks.cacheGroups.common.test = module => !sourcePolicy(module.resource);
      }
      return {plugins: isServer ? [] : [{
        apply(compiler) {
          compiler.hooks.afterEmit.tap('PortalPermissions', compilation => {
            chunks = {};
            emitted = {};
            for (const chunk of compilation.chunks) {
              const modules = [...compilation.chunkGraph.getChunkModulesIterable(chunk)];
              const policy = isolatedPolicy(modules.map(m => sourcePolicy(m.resource)), chunk.name || chunk.id);
              if (policy && chunk.canBeInitial()) throw new Error('Restricted training content entered an initial/shared bundle');
              for (const file of chunk.files) chunks[file] = policy;
            }
            for (const module of compilation.modules) {
              const resource = module.resource || '';
              const owners = [];
              for (const connection of compilation.moduleGraph.getIncomingConnections(module)) {
                owners.push(sourcePolicy(connection.originModule?.resource));
              }
              if (!owners.some(Boolean)) owners.push(sourcePolicy(resource));
              const filenames = [module.buildInfo?.filename, ...Object.keys(module.buildInfo?.assets || {})].filter(Boolean);
              for (const file of filenames) emitted[file] = unique([...(emitted[file] || []), ...owners]);
            }
          });
        },
      }]};
    },
    injectHtmlTags() {
      return {headTags: [
        {tagName: 'link', attributes: {rel: 'stylesheet', href: `${BASE}portal/lesson.css`}},
      ], postBodyTags: [
        {tagName: 'script', attributes: {src: `${BASE}portal/tracker.js`, type: 'module'}},
      ]};
    },
    async postBuild({outDir}) {
      const metadataDir = path.join(context.generatedFilesDir, 'docusaurus-plugin-content-docs/default');
      const docs = [];
      for (const file of await fs.readdir(metadataDir)) {
        if (!file.endsWith('.json')) continue;
        const data = JSON.parse(await fs.readFile(path.join(metadataDir, file), 'utf8'));
        if (!data.source || !data.permalink) continue;
        const canonical = data.permalink.endsWith('/') ? data.permalink : `${data.permalink}/`;
        docs.push({path: canonical, title: data.title, policy: sourcePolicy(data.source), source: data.source});
      }
      const pages = Object.fromEntries(docs.map(d => [d.path.endsWith('/') ? d.path : `${d.path}/`, {title: d.title, policy: d.policy}]));
      const modules = [];
      for (const doc of docs) {
        if (!doc.policy || !/\/README\.md$/.test(doc.source)) continue;
        modules.push({id: doc.policy.module, title: doc.title, path: doc.path,
          pages: docs.filter(d => d.policy?.module === doc.policy.module).map(d => ({path: d.path, title: d.title, solution: d.policy.solution}))});
      }
      const moduleNumber = id => Number(id.match(/^module(\d+(?:_\d+)?)/)?.[1]?.replace('_', '.') || 0);
      modules.sort((a,b) => moduleNumber(a.id) - moduleNumber(b.id) || a.id.localeCompare(b.id));
      const assets = {};
      for (const file of await files(outDir)) {
        if (/\.map$|(^|\/)(sitemap|search-index)|docusaurus-debug/.test(file)) throw new Error(`Unexpected sensitive artifact: ${file}`);
        if (file.endsWith('.html')) {
          const route = routeForFile(file);
          // The public landing page and errors are generated by the Worker.
          if (!pages[route]) continue;
          const entry = {file: `/${file}`, policy: pages[route].policy};
          assets[route] = entry;
          assets[BASE + file] = entry;
        } else if (Object.hasOwn(chunks, file)) {
          assets[BASE + file] = {file: `/${file}`, policy: chunks[file]};
        } else if (file.endsWith('.LICENSE.txt') && Object.hasOwn(chunks, file.replace(/\.LICENSE\.txt$/, ''))) {
          assets[BASE + file] = {file: `/${file}`, policy: chunks[file.replace(/\.LICENSE\.txt$/, '')]};
        } else if (Object.hasOwn(emitted, file)) {
          assets[BASE + file] = {file: `/${file}`, anyOf: emitted[file]};
        } else if (['img/avatar.jpg', 'img/favicon.png', 'img/social-card.jpg'].includes(file)) {
          assets[BASE + file] = {file: `/${file}`, policy: null};
        } else {
          // Unknown output is never automatically exposed.
          throw new Error(`Unclassified build artifact: ${file}`);
        }
      }
      for (const route of Object.keys(pages)) if (!assets[route]) throw new Error(`Missing protected page: ${route}`);
      const site = {assets, pages, modules};
      const generated = path.resolve(__dirname, '../generated');
      await fs.mkdir(generated, {recursive: true});
      await fs.writeFile(path.join(generated, 'site.json'), JSON.stringify(site, null, 2));
      await fs.writeFile(path.join(generated, 'site.mjs'), `export default ${JSON.stringify(site)};\n`);
      console.log(`Portal manifest: ${docs.length} pages, ${modules.length} modules, ${Object.keys(assets).length} protected paths`);
    },
  };
};
